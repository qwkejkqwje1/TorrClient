package main

// Версия формата файлов состояния.
//
// Файлы viewed.json, userdata.json и subscriptions.json хранят то, что
// восстановить нечем: отметки просмотра, избранное, закладки, подборки,
// подписки. Читать их должна вторая копия программы, а формат меняется.
//
// Без номера версии старый файл читается, пока не повезёт. Сегодня это
// работает, потому что новые поля просто добавляются и старые лишними не
// мешают. Но первое же переименование ключа или смена типа молча испортит
// данные: демон прочитает не то поле и перезапишет файл своим.
//
// Поэтому версия пишется при каждом сохранении и проверяется при чтении:
// файл без номера — формата 1, на котором всё и писалось до этого поля.
// Файл с большим номером читаться отказывается: значит, его писала новее
// программа, и молча читать его как свой формат нельзя.

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
)

// stateFormat — текущий формат файлов состояния. Поднимается на единицу при
// каждом несовместимом изменении: переименование ключа, смена типа, иная
// разметка списка. Добавление нового поля версию не поднимает — старый файл
// при этом читается как есть, и новые поля в нём просто отсутствуют.
const stateFormat = 1

// stateDoc — версия в обёртке файла состояния.
//
// Своя структура вместо поля прямо в UserData: у каждого файла своя форма, и
// версия должна быть общей частью их чтения, а не полем в каждом. При этом
// вложенность «version» позволяет добавить сведения о том, кто и когда
// записал файл, не затрагивая сами данные.
type stateDoc struct {
	Version int `json:"version"`
	// Data — полезная нагрузка в исходном виде. Дальше её разбирает владелец
	// формата: общая часть не должна знать, что внутри избранного.
	Data json.RawMessage `json:"data"`
}

// readStateDoc читает файл состояния и достаёт его версию.
//
// Отказ при слишком новой версии — осознанный: читать незнакомый формат значит
// превратить содержимое в мусор при следующей же записи. Лучше сказать, чем
// потерять данные. Отсутствующий файл ошибкой не считается — его читатель
// создаёт пустой склад сам, как и прежде.
func readStateDoc(path string, v any) error {
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	// Сначала пробуем обёртку с версией. Такой файл — единственный, у кого
	// есть номер; всё остальное пришло из прежних сборок.
	var doc stateDoc
	if err := json.Unmarshal(b, &doc); err == nil && doc.Version > 0 {
		if doc.Version > stateFormat {
			return fmt.Errorf("%s: файл записан более новой версией программы (формат %d, умеем %d) — оставлен как есть",
				filepath.Base(path), doc.Version, stateFormat)
		}
		if len(doc.Data) == 0 {
			// Версия есть, а данных нет: файл записан нами же, но пуст.
			return nil
		}
		return json.Unmarshal(doc.Data, v)
	}
	// Файла без номера не бывает: он всегда пишется с версией. Отсутствие
	// номера означает старый формат, который читается как был.
	if err := json.Unmarshal(b, v); err != nil {
		return err
	}
	return nil
}

// writeStateDoc пишет файл состояния с номером формата.
func writeStateDoc(path string, v any) error {
	raw, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return err
	}
	b, err := json.MarshalIndent(stateDoc{Version: stateFormat, Data: raw}, "", "  ")
	if err != nil {
		return err
	}
	return writeFileAtomic(path, b, 0o600)
}
